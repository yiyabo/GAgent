@dataclass
class ComplianceCheckResult:
    is_violation: bool
    category_id: Optional[str] = None
    category_name: Optional[str] = None
    matched_keywords: List[str] = field(default_factory=list)
    matched_patterns: List[str] = field(default_factory=list)
    has_adversarial_framing: bool = False
    risk_summary: Optional[str] = None
    suggested_refusal_reason: Optional[str] = None
    safe_alternative_direction: Optional[str] = None


def check_compliance_intent(text: str) -> ComplianceCheckResult:
    """Scan input text against the compliance lexicon and adversarial patterns."""
    if not text or not isinstance(text, str):
        return ComplianceCheckResult(is_violation=False)

    normalized_text = text.strip()
    
    has_adversarial = any(bool(re.search(pat, normalized_text)) for pat in ADVERSARIAL_FRAMINGS)
    
    for cat_key, cat_data in COMPLIANCE_LEXICON.items():
        matched_kw = [kw for kw in cat_data["keywords"] if kw in normalized_text]
        matched_pat = [pat for pat in cat_data["patterns"] if re.search(pat, normalized_text)]
        
        if matched_pat or (len(matched_kw) >= 2) or (matched_kw and has_adversarial):
            cat_name = cat_data["name"]
            cat_risk = cat_data["core_risk"]
            return ComplianceCheckResult(
                is_violation=True,
                category_id=cat_data["id"],
                category_name=cat_name,
                matched_keywords=matched_kw,
                matched_patterns=matched_pat,
                has_adversarial_framing=has_adversarial,
                risk_summary=cat_risk,
                suggested_refusal_reason=f"该请求涉及【{cat_name}】风险（{cat_risk}），模型不可提供可操作性的违规、侵权或规避指导。",
                safe_alternative_direction="建议转向合法合规渠道，如正规公开数据调研、法定知识产权注册与授权保护、正规招投标及合规商业分析流程。"
            )

    return ComplianceCheckResult(is_violation=False)


