def _watermark_pdf(source_path: Path, target_path: Path) -> None:
    try:
        from pypdf import PdfReader, PdfWriter
        from reportlab.lib.colors import Color
        from reportlab.lib.pagesizes import landscape, portrait
        from reportlab.pdfbase.pdfmetrics import stringWidth
        from reportlab.pdfgen import canvas
    except ImportError:
        logger.warning("PDF watermark skipped (deps unavailable): %s", source_path)
        _copy_fallback(source_path, target_path)
        return

    try:
        reader = PdfReader(str(source_path))
        writer = PdfWriter()
        for page in reader.pages:
            width = float(page.mediabox.width)
            height = float(page.mediabox.height)
            page_size = landscape((width, height)) if width > height else portrait((width, height))
            buffer = tempfile.SpooledTemporaryFile()
            overlay = canvas.Canvas(buffer, pagesize=page_size)
            font_size = max(7, min(width, height) / 70)
            overlay.setFont("Helvetica", font_size)
            overlay.setFillColor(Color(0.6, 0.6, 0.6, alpha=0.7))
            text_width = stringWidth(WATERMARK_TEXT, "Helvetica", font_size)
            overlay.drawString(max(8, width - text_width - 8), 8, WATERMARK_TEXT)
            overlay.save()
            buffer.seek(0)
            page.merge_page(PdfReader(buffer).pages[0])
            writer.add_page(page)
        writer.add_metadata({"/Watermark": WATERMARK_TEXT})
        with target_path.open("wb") as handle:
            writer.write(handle)
        _copy_metadata(source_path, target_path)
    except Exception:
        logger.warning("PDF watermark skipped (render failed): %s", source_path)
        _copy_fallback(source_path, target_path)


_HANDLERS = {
    ".md": _watermark_markdown,
    ".markdown": _watermark_markdown,
    ".txt": _watermark_text,
    ".png": _watermark_png,
    ".jpg": _watermark_jpeg,
    ".jpeg": _watermark_jpeg,
}


def apply_watermark(source_path: Path, target_path: Path) -> Path:
    """Inject a watermark from ``source_path`` into ``target_path`` by extension.

    Unsupported types fall back to ``shutil.copy2``. Any watermarking error falls
    back to a plain copy so the deliverable pipeline is never interrupted.
    Returns ``target_path``.
    """
    source_path = Path(source_path)
    target_path = Path(target_path)
    ext = source_path.suffix.lower()
    try:
        if ext == ".pdf":
            _watermark_pdf(source_path, target_path)
        else:
            handler = _HANDLERS.get(ext)
            if handler is None:
                _copy_fallback(source_path, target_path)
            else:
                handler(source_path, target_path)
    except Exception as e:
        logger.warning("Watermark failed for %s, fallback to copy: %s", source_path, e)
        try:
            _copy_fallback(source_path, target_path)
        except Exception as copy_err:
            logger.warning("Copy fallback also failed for %s: %s", source_path, copy_err)
            raise
    return target_path


def apply_watermark_inplace(path: Path) -> None:
    """Inject a watermark in place via a temp file then ``os.replace``."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(path)
    fd, tmp_name = tempfile.mkstemp(suffix=path.suffix, dir=str(path.parent))
    tmp_path = Path(tmp_name)
    try:
        os.close(fd)
        apply_watermark(path, tmp_path)
        os.replace(tmp_path, path)
    except Exception:
        if tmp_path.exists():
            try:
                tmp_path.unlink()
            except Exception:
                pass
        raise
